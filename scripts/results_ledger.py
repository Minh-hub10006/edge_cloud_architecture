"""Consolidated benchmark ledger from raw run files collected per host.

    python -B scripts/results_ledger.py results            # -> results/BENCHMARK_RESULTS.md (+ .csv)

Layout: results/<host>/<release>/runs/bench/<campaign>/<model>/<model|pipeline>/<step>/.../summary.json
Cloud receiver resources: results/cloud-*/**/cloud-resources-<model>-*.jsonl (matched by time window).
Each campaign/model/scope is aggregated with benchmark.report exactly like bench.sh report.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
import re
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from benchmark import report  # noqa: E402

TOTALS = {"adapter_call_ms", "adapter_reported_ms", "edge_adapter_call_ms", "edge_adapter_reported_ms",
          "request_rtt_ms", "e2e_ms", "cloud_service_ms"}


def scope_dirs(root: Path):
    for scope in sorted(root.glob("*/*/runs/bench/*/*/*")):  # edge-* and cloud-* hosts
        if scope.is_dir() and scope.name in {"model", "pipeline"}:
            host, release, _, _, campaign, model = scope.parts[-7:-1]
            yield host, release, campaign, model, scope


def cloud_file(root: Path, model: str, tmp: Path) -> Path | None:
    # Rows are windowed by each run's ByteTrack interval, so merging every file of the model is safe.
    files = sorted(root.glob(f"cloud-*/**/cloud-resources-{model}-*.jsonl"))
    if not files:
        return None
    merged = tmp / f"{model}.jsonl"
    merged.write_text("".join(f.read_text(encoding="utf-8") for f in files), encoding="utf-8")
    return merged


def f(value, digits=1):
    return "-" if value is None else f"{value:.{digits}f}"


def build(root: Path) -> tuple[list[str], list[dict]]:
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for host, release, campaign, model, scope in scope_dirs(root):
            cloud = cloud_file(root, model, Path(tmp)) if scope.name == "pipeline" else None
            runs = report.load_runs([scope], cloud)
            for row in report.aggregate(runs):
                sched = scope.parent / "edge_sched.txt"
                group = [r["summary"] for r in runs if r["summary"].get("measured_frames") == row["measured_frames"]
                         and r["summary"].get("model_key") == row["model_key"]]
                measured = sum(x.get("measured_frames") or 0 for x in group)
                # Reason category only ("cloud:media_disconnected"), not the per-frame detail text.
                losses = {}
                for x in group:
                    for reason, count in (x.get("failure_reasons") or {}).items():
                        key = ":".join(reason.split(":")[:2])
                        losses[key] = losses.get(key, 0) + count
                rows.append({"host": host, "release": release, "campaign": campaign, "model": model,
                             "sched": sched.read_text(encoding="utf-8").strip() if sched.is_file() else None,
                             "completion": sum(x.get("completed") or 0 for x in group) / measured if measured else None,
                             "loss_reasons": losses, **row})
    rows.sort(key=lambda r: (r["host"], r["model"], r["profile"], r["release"], r["campaign"],
                             -(r["measured_frames"] or 0)))
    lines = ["# Benchmark results (raw-file ledger)", "",
             f"Generated by `scripts/results_ledger.py` from `{root.name}/`. Official = 10000 frames x 3 reps; "
             "smoke/1k rows are sweeps (PROVISIONAL by design). Campaign names other than timestamps are "
             "named experiments (e.g. boost, cap, 8core) and are not the standard configuration.", "",
             "## 1. Official runs (10000 frames)", "",
             "| Host | Release | Campaign | Model | Scope | Inflight | Reps ok | FPS | CV | ByteTrack FPS "
             "| e2e p95 ms | Bottleneck lane (cap FPS, load) | CPU % | Temp max C | GPU % | Gate |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["measured_frames"] != 10000:
            continue
        lane = r["lanes"][0] if r["lanes"] else None
        neck = "-" if not lane else (f"{lane['lane']} ({f(lane['fps_cap'])}, "
                                     f"{'-' if lane['load'] is None else f'{lane['load'] * 100:.0f}%'})")
        gpu = r["cloud_gpu_util_mean_pct"] if r["cloud_gpu_util_mean_pct"] is not None else r["local_gpu_util_mean_pct"]
        cv = "-" if r["effective_fps_cv"] is None else f"{r['effective_fps_cv'] * 100:.1f}%"
        lines.append(f"| {r['host']} | {r['release']} | {r['campaign']} | {r['model_key']} | {r['profile']} "
                     f"| {r['max_inflight'] or '-'} | {r['passed']}/{r['repetitions']} | {f(r['effective_fps_mean'])} "
                     f"| {cv} | {f(r['bytetrack_fps_mean'])} | {f(r['e2e_p95_ms'])} | {neck} "
                     f"| {f(r['edge_cpu_mean_pct'])} | {f(r['edge_temp_max_c'])} | {f(gpu)} | {r['gate']} |")
    lines += ["", "GPU % = Cloud GPU for pipeline runs with Cloud resources, otherwise the local GPU (Edge247).", "",
              "## 2. Pipeline / model capacity (same host and model, newest official run of each)", "",
              "| Host | Model | Model capacity FPS | Pipeline FPS (inflight) | Ratio |", "|---|---|---|---|---|"]
    newest = {}
    for r in rows:
        if r["measured_frames"] == 10000 and r["passed"] and re.fullmatch(r"\d{8}_\d{6}", r["campaign"]):
            kind = "model" if r["profile"].startswith("model") else "pipeline"
            key = (r["host"], r["model"], kind)
            # Campaign names are YYYYMMDD_HHMMSS start times; release folder names do not sort by age.
            if key not in newest or r["campaign"] > newest[key]["campaign"]:
                newest[key] = r
    for (host, model, kind), r in sorted(newest.items()):
        if kind != "pipeline":
            continue
        # Cloud-placed models: capacity is measured on the Cloud host that runs them.
        cap = newest.get((host, model, "model")) or next(
            (v for (h, m, k), v in newest.items() if h.startswith("cloud-") and m == model and k == "model"), None)
        ratio = f"{r['effective_fps_mean'] / cap['effective_fps_mean'] * 100:.0f}%" if cap else "-"
        source = "" if not cap or cap["host"] == host else f" ({cap['host']})"
        lines.append(f"| {host} | {model} | {f(cap['effective_fps_mean']) + source if cap else '- (not measured)'} "
                     f"| {f(r['effective_fps_mean'])} ({r['max_inflight']}) | {ratio} |")
    lines += ["", "## 3. Contention scenarios (several Edges on one Cloud model at once)", "",
              "Each repetition runs the same wall-clock slot on every Edge (bench.sh contention); "
              "compare with the single-Edge pipeline rows above.", "",
              "| Campaign | Host | Model | Frames/rep | Reps ok | FPS | CV | ByteTrack FPS | e2e p95 ms "
              "| Bottleneck lane (cap FPS, load) | Completed | Frame loss reasons | Gate |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted((r for r in rows if r["campaign"].startswith("contention_")),
                    key=lambda r: (r["campaign"], r["model"], r["host"])):
        lane = r["lanes"][0] if r["lanes"] else None
        neck = "-" if not lane else (f"{lane['lane']} ({f(lane['fps_cap'])}, "
                                     f"{'-' if lane['load'] is None else f'{lane['load'] * 100:.0f}%'})")
        cv = "-" if r["effective_fps_cv"] is None else f"{r['effective_fps_cv'] * 100:.1f}%"
        lines.append(f"| {r['campaign']} | {r['host']} | {r['model_key']} | {r['measured_frames']} "
                     f"| {r['passed']}/{r['repetitions']} | {f(r['effective_fps_mean'])} | {cv} "
                     f"| {f(r['bytetrack_fps_mean'])} | {f(r['e2e_p95_ms'])} | {neck} "
                     f"| {'-' if r['completion'] is None else f'{r['completion'] * 100:.1f}%'} "
                     f"| {', '.join(f'{k} x{v}' for k, v in sorted(r['loss_reasons'].items())) or '-'} "
                     f"| {r['gate']} |")
    lines += ["", "## 4. Per-run detail (every stage and lane)", ""]
    for r in rows:
        lines += [f"### {r['host']} · {r['release']} · {r['campaign']} · {r['model_key']} · {r['profile']} · "
                  f"inflight {r['max_inflight'] or '-'} · {r['measured_frames']} frames · {r['gate']}", "",
                  f"FPS {f(r['effective_fps_mean'])} (reps ok {r['passed']}/{r['repetitions']}, CV "
                  f"{'-' if r['effective_fps_cv'] is None else f'{r['effective_fps_cv'] * 100:.1f}%'}), "
                  f"ByteTrack FPS {f(r['bytetrack_fps_mean'])}, CPU {f(r['edge_cpu_mean_pct'])}%, "
                  f"temp max {f(r['edge_temp_max_c'])} C."]
        if r["failures"]:
            lines.append(f"Failures: {'; '.join(r['failures'])}")
        if r["sched"]:
            lines += ["", "```", r["sched"], "```"]
        lines += ["", "| Stage | p50 ms | p95 ms | |", "|---|---|---|---|"]
        lines += [f"| {s['stage']} | {f(s['p50_ms'], 2)} | {f(s['p95_ms'], 2)} | "
                  f"{'total (wraps others)' if s['stage'] in TOTALS else ''} |" for s in r["stages"]]
        lines += ["", "| Lane | Stages | Busy p50 ms | FPS cap | Load |", "|---|---|---|---|---|"]
        lines += [f"| {'**' + l['lane'] + '**' if i == 0 else l['lane']} | {'+'.join(l['stages'])} "
                  f"| {f(l['busy_p50_ms'], 2)} | {f(l['fps_cap'])} "
                  f"| {'-' if l['load'] is None else f'{l['load'] * 100:.0f}%'} |" for i, l in enumerate(r["lanes"])]
        lines.append("")
    return lines, rows


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    args = parser.parse_args(argv)
    lines, rows = build(args.root)
    (args.root / "BENCHMARK_RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with (args.root / "BENCHMARK_RESULTS.csv").open("w", encoding="utf-8", newline="") as target:
        fields = ["host", "release", "campaign", "model_key", "profile", "max_inflight", "measured_frames",
                  "repetitions", "passed", "effective_fps_mean", "effective_fps_cv", "bytetrack_fps_mean",
                  "e2e_p95_ms", "bottleneck", "edge_cpu_mean_pct", "edge_temp_max_c", "local_gpu_util_mean_pct",
                  "cloud_gpu_util_mean_pct", "gate"]
        writer = csv.DictWriter(target, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{len(rows)} groups -> {args.root / 'BENCHMARK_RESULTS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
